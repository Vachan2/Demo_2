"""
Patch validator for Demo 2.

Runs the user-service test suite as subprocesses from within the
service's own directory.  Reports pass/fail per check so the pipeline
can display granular results.

Checks (in order)
-----------------
1. lint          — ruff check (falls back to flake8 if ruff absent)
2. unit          — pytest unit tests (no live infra required)
3. integration   — pytest integration tests (needs Postgres + Redis;
                   treated as best-effort — failure doesn't block the pipeline)
4. cache_regression — pytest tests/test_cache_key_regression.py
                      (the test generated by the remediation module)
"""
from __future__ import annotations

import asyncio
import logging
import re
import subprocess
import time
from pathlib import Path

from config import settings
from models import CheckResult, Incident, ValidationResult

log = logging.getLogger("sentinel.validator")

_REPO_PATH = Path(settings.local_repo_path).resolve()


# ── subprocess helper ─────────────────────────────────────────────────────────

def _run(cmd: list[str], cwd: Path, timeout: int = 60) -> tuple[int, str]:
    """Run *cmd* in *cwd* and return (returncode, combined output)."""
    try:
        result = subprocess.run(
            cmd,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=timeout,
        )
        output = (result.stdout + result.stderr).strip()
        return result.returncode, output
    except subprocess.TimeoutExpired:
        return 1, f"TIMEOUT after {timeout}s"
    except FileNotFoundError as exc:
        return 1, f"command not found: {exc}"


async def _run_async(cmd: list[str], cwd: Path, timeout: int = 60) -> tuple[int, str]:
    loop = asyncio.get_event_loop()
    return await loop.run_in_executor(None, _run, cmd, cwd, timeout)


# ── individual checks ─────────────────────────────────────────────────────────

async def _check_lint() -> CheckResult:
    t0 = time.monotonic()
    # Try ruff first, fall back to flake8
    code, out = await _run_async(["ruff", "check", "."], _REPO_PATH)
    if code == 127 or "command not found" in out.lower():
        code, out = await _run_async(["flake8", "."], _REPO_PATH)
        tool = "flake8"
    else:
        tool = "ruff"

    passed = code == 0
    return CheckResult(
        name=f"lint ({tool})",
        passed=passed,
        output=out[:1000] if not passed else f"{tool}: no issues found",
        duration_s=round(time.monotonic() - t0, 2),
    )


async def _check_unit() -> CheckResult:
    t0 = time.monotonic()
    code, out = await _run_async(
        [
            "pytest",
            "tests/test_user_service.py",
            "tests/test_api.py",
            "-v",
            "--tb=short",
            "--no-header",
        ],
        _REPO_PATH,
        timeout=60,
    )
    passed = code == 0
    summary = _extract_pytest_summary(out)
    return CheckResult(
        name="unit tests",
        passed=passed,
        output=summary or out[-800:],
        duration_s=round(time.monotonic() - t0, 2),
    )


async def _check_integration() -> CheckResult:
    """
    Integration tests need a live Postgres + Redis.  Best-effort: a failure
    here is logged but does not fail the overall validation.
    """
    t0 = time.monotonic()
    code, out = await _run_async(
        [
            "pytest",
            "tests/test_integration.py",
            "-v",
            "--tb=short",
            "--no-header",
        ],
        _REPO_PATH,
        timeout=90,
    )
    passed = code == 0
    summary = _extract_pytest_summary(out)
    return CheckResult(
        name="integration tests (best-effort)",
        passed=passed,
        output=summary or out[-800:],
        duration_s=round(time.monotonic() - t0, 2),
    )


async def _check_cache_regression() -> CheckResult:
    """
    Run the regression test that Sentinel itself generated.
    This is the critical gate — it must pass before the incident is resolved.
    """
    t0 = time.monotonic()

    regression_file = _REPO_PATH / "tests" / "test_cache_key_regression.py"
    if not regression_file.exists():
        return CheckResult(
            name="cache-key regression",
            passed=False,
            output="tests/test_cache_key_regression.py not found — "
                   "remediation may not have been applied yet",
            duration_s=round(time.monotonic() - t0, 2),
        )

    code, out = await _run_async(
        [
            "pytest",
            "tests/test_cache_key_regression.py",
            "-v",
            "--tb=short",
            "--no-header",
        ],
        _REPO_PATH,
        timeout=60,
    )
    passed = code == 0
    summary = _extract_pytest_summary(out)
    return CheckResult(
        name="cache-key regression",
        passed=passed,
        output=summary or out[-800:],
        duration_s=round(time.monotonic() - t0, 2),
    )


def _extract_pytest_summary(output: str) -> str:
    """Pull the '== N passed / N failed ==' line from pytest output."""
    for line in reversed(output.splitlines()):
        if re.search(r"\d+ (passed|failed|error)", line):
            return line.strip()
    return ""


# ── Public entry point ────────────────────────────────────────────────────────

async def run_all(incident: Incident) -> ValidationResult:
    """
    Run all validation checks and return an aggregated ValidationResult.

    lint + unit + cache_regression must all pass.
    integration is best-effort and does not affect the overall result.
    """
    log.info("validation started", extra={"incident_id": incident.id})

    # Run lint and unit in parallel; cache_regression depends on remediation
    lint_result, unit_result = await asyncio.gather(
        _check_lint(),
        _check_unit(),
    )

    # Integration: best-effort, run concurrently with cache regression
    integration_result, regression_result = await asyncio.gather(
        _check_integration(),
        _check_cache_regression(),
    )

    checks = [lint_result, unit_result, integration_result, regression_result]

    # Overall pass = lint AND unit AND cache regression (integration best-effort)
    passed = lint_result.passed and unit_result.passed and regression_result.passed

    total = len(checks)
    n_passed = sum(1 for c in checks if c.passed)

    summary_parts = []
    for c in checks:
        icon = "✅" if c.passed else ("⚠️" if "best-effort" in c.name else "❌")
        summary_parts.append(f"{icon} {c.name} ({c.duration_s:.1f}s)")

    summary = f"{n_passed}/{total} checks passed\n" + "\n".join(summary_parts)

    log.info(
        "validation complete",
        extra={
            "incident_id": incident.id,
            "passed": passed,
            "checks_passed": n_passed,
            "checks_total": total,
        },
    )

    return ValidationResult(
        passed=passed,
        checks=checks,
        summary=summary,
    )
