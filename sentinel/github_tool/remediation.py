def _make_profile(user_id: int) -> dict:
    return {{
        "id": user_id,
        "username": f"user{{user_id}}",
        "email": f"user{{user_id}}@example.com",
        "full_name": f"Demo User {{user_id}}",
        "created_at": "2024-01-01T00:00:00",
    }}


# ---------------------------------------------------------------------------
# Unit tests (no live Redis or Postgres required)
# ---------------------------------------------------------------------------

class TestCacheKeyVersion:
    """The cache key must always use the :v1 suffix."""

    def test_healthy_cache_key_uses_v1(self):
        """Directly import and verify the key constant."""
        import user_service
        assert user_service.CACHE_KEY_VERSION_HEALTHY == "v1", (
            "Cache key version must be 'v1'. "
            "A different value will cause a cache-miss stampede."
        )

    def test_cache_key_format(self):
        """Key format must match user:{{id}}:profile:v1."""
        import user_service
        key = user_service._healthy_cache_key("42")
        assert key == "user:42:profile:v1", (
            f"Expected 'user:42:profile:v1', got '{{key}}'"
        )

    def test_no_v2_key_in_active_code_path(self):
        """Buggy :v2 key must not be reachable from the public facade."""
        import inspect
        import user_service
        source = inspect.getsource(user_service.get_user_profile)
        assert "v2" not in source, (
            "get_user_profile() must not reference the :v2 cache key"
        )


class TestCacheHitPath:
    """get_user_profile_healthy must return a cache hit on the second call."""

    @pytest.mark.asyncio
    async def test_second_call_is_cache_hit(self):
        profile = _make_profile(1)

        fake_redis = mock.AsyncMock()
        # First call: MISS, second call: HIT
        fake_redis.get.side_effect = [None, json.dumps(profile)]
        fake_redis.setex = mock.AsyncMock()

        fake_pool = mock.MagicMock()
        fake_conn = mock.AsyncMock()
        fake_conn.fetchrow.return_value = {{
            "id": 1,
            "username": "user1",
            "email": "user1@example.com",
            "full_name": "Demo User 1",
            "created_at": mock.MagicMock(isoformat=lambda: "2024-01-01T00:00:00"),
        }}
        fake_pool.acquire.return_value.__aenter__ = mock.AsyncMock(
            return_value=fake_conn
        )
        fake_pool.acquire.return_value.__aexit__ = mock.AsyncMock(
            return_value=False
        )

        with mock.patch("user_service.get_redis", return_value=fake_redis):
            with mock.patch("user_service.get_pool", return_value=fake_pool):
                import user_service

                # First call — cache miss, DB fetch
                _p1, hit1 = await user_service.get_user_profile_healthy("1")
                assert not hit1, "First call should be a cache miss"

                # Second call — cache hit (mock returns stored value)
                _p2, hit2 = await user_service.get_user_profile_healthy("1")
                assert hit2, "Second call should be a cache hit"

    @pytest.mark.asyncio
    async def test_cache_key_written_with_v1_suffix(self):
        """After a DB fetch, the key stored in Redis must end with :v1."""
        profile = _make_profile(7)
        stored_keys: list[str] = []

        fake_redis = mock.AsyncMock()
        fake_redis.get.return_value = None  # always miss

        async def capture_setex(key, ttl, value):
            stored_keys.append(key)

        fake_redis.setex.side_effect = capture_setex

        fake_pool = mock.MagicMock()
        fake_conn = mock.AsyncMock()
        fake_conn.fetchrow.return_value = {{
            "id": 7,
            "username": "user7",
            "email": "user7@example.com",
            "full_name": "Demo User 7",
            "created_at": mock.MagicMock(isoformat=lambda: "2024-01-01T00:00:00"),
        }}
        fake_pool.acquire.return_value.__aenter__ = mock.AsyncMock(
            return_value=fake_conn
        )
        fake_pool.acquire.return_value.__aexit__ = mock.AsyncMock(
            return_value=False
        )

        with mock.patch("user_service.get_redis", return_value=fake_redis):
            with mock.patch("user_service.get_pool", return_value=fake_pool):
                import user_service
                await user_service.get_user_profile_healthy("7")

        assert len(stored_keys) == 1
        assert stored_keys[0].endswith(":v1"), (
            f"Cache key must end with :v1, got: {{stored_keys[0]}}"
        )


