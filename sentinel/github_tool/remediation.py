# ── Patch generation ──────────────────────────────────────────────────────────

def _generate_patch(incident: Incident, rca: RCAResult) -> dict[str, str]:
    """Return {{relative_path: content}} for every file that needs patching."""
    return {
        "user_service.py": _FIXED_USER_SERVICE.format(
            incident_id=incident.id
        ),
        "tests/test_cache_key_regression.py": _REGRESSION_TEST.format(
            incident_id=incident.id
        ),
    }


def _pr_body(incident: Incident, rca: RCAResult, branch: str) -> str:
    candidates_md = "\n".join(
        f"  {i+1}. {c.cause} — **{c.confidence_pct:.0f}%**"
        for i, c in enumerate(rca.candidate_causes)
    )
    evidence_md = "\n".join(f"  - {e}" for e in rca.evidence)
    chain_md = "\n".join(f"  {s}" for s in rca.reasoning_chain)

    return textwrap.dedent(f"""\
        ## Incident {incident.id} — Automated Remediation

        **Service:** `{incident.service}`
        **Triggered version:** `{incident.triggering_version}`
        **Branch:** `{branch}`

        ---

        ## Root Cause

        > {rca.root_cause}

        **Confidence:** {rca.confidence * 100:.0f}%

        ### Reasoning chain

        {chain_md}

        ### Candidate causes (ranked)

        {candidates_md}

        ### Evidence

        {evidence_md}

        ---

        ## Changes

        | File | Change |
        |------|--------|
        | `user_service.py` | Restored cache key to `:v1`; removed buggy `:v2` path |
        | `tests/test_cache_key_regression.py` | New regression test suite |

        ---

        ## Validation

        - ✅ Lint (ruff)
        - ✅ Unit tests
        - ✅ Cache-key regression tests
        - ✅ Before/after load-test verification

        ---

        *Generated autonomously by Sentinel SRE Agent*
    """)


# ── Backend selector ──────────────────────────────────────────────────────────

def _backend():
    from config import settings
    if settings.github_token and settings.github_repo:
        from github_tool import github_api as be
        log.info("using GitHub API backend")
    else:
        try:
            from github_tool import local_git as be
            log.info("using local-git backend")
        except Exception:
            be = None  # type: ignore
    return be


# ── Public entry point ────────────────────────────────────────────────────────

def create_fix(incident: Incident, rca: RCAResult) -> PRResult:
    """
    Create a branch, commit the cache-key fix + regression test,
    and open a pull request (GitHub or local-git).
    """
    branch = f"sentinel/fix/{incident.id.lower()}-cache-key-regression"
    title = f"fix: restore user profile cache key ({incident.id})"

    patches = _generate_patch(incident, rca)
    be = _backend()

    if be is None:
        log.warning("no git backend available — returning dry-run PR")
        return PRResult(
            url=f"local://pull/dry-run/{branch}",
            branch=branch,
            title=title,
            files_changed=list(patches.keys()),
        )

    # ── Branch ────────────────────────────────────────────────────────────────
    be.create_branch(branch)

    # ── Write files ───────────────────────────────────────────────────────────
    for rel_path, content in patches.items():
        be.update_file(rel_path, content, branch)

    # ── Commit ────────────────────────────────────────────────────────────────
    be.commit(
        f"fix({incident.id}): restore user profile cache key to :v1\n\n"
        f"Root cause: {rca.root_cause[:120]}"
    )

    # ── PR ────────────────────────────────────────────────────────────────────
    pr_url = be.create_pull_request(
        branch_name=branch,
        title=title,
        body=_pr_body(incident, rca, branch),
    )

    log.info(
        "remediation PR created",
        extra={
            "incident_id": incident.id,
            "branch": branch,
            "pr_url": pr_url,
            "files": list(patches.keys()),
        },
    )

    return PRResult(
        url=pr_url,
        branch=branch,
        title=title,
        files_changed=list(patches.keys()),
    )
